create index "RevisionEstacionesClaves_idx_revision_estacion" on public."RevisionEstacionesClaves" (revision_estacion_id);
create index "RevisionEstacionesClaves_idx_clave" on public."RevisionEstacionesClaves" (clave_id);
-- 9) Vista util para listado rapido por servicio
create view public."vw_bitacora_servicio_estado" with (security_invoker = true) as
select s.id as servicio_id,
    s.folio,
    s.fecha_servicio,
    s.direccion_id,
    b.id as bitacora_id,
    b.tipo as tipo_bitacora,
    rb.id as revision_id,
    rb.estado as estado_revision,
    rb.no_hay_bitacora_disponible
from public."Servicios" s
    left join public."Bitacoras" b on b.direccion_id = s.direccion_id
    and b.organizacion = s.organizacion
    and b.estado = 'activa'
    left join public."RevisionesBitacora" rb on rb.servicio_id = s.id
    and rb.bitacora_id = b.id;
-- 10) Helpers de seguridad para RLS
create or replace function public.user_belongs_to_org(_organizacion text) returns boolean language sql stable security definer
set search_path = public as $$
select exists (
        select 1
        from public."Empleados" e
        where e.user_id = auth.uid()
            and e.organizacion = _organizacion
            and coalesce(e.activo, true) = true
    );
$$;
create or replace function public.user_is_org_admin(_organizacion text) returns boolean language sql stable security definer
set search_path = public as $$
select exists (
        select 1
        from public."Empleados" e
        where e.user_id = auth.uid()
            and e.organizacion = _organizacion
            and coalesce(e.activo, true) = true
            and e.tipo_rol in ('administrador', 'superadmin')
    );
$$;
