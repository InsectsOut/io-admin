create index "RevisionEstaciones_idx_revision" on public."RevisionEstacionesBitacora" (revision_id);
create index "RevisionEstaciones_idx_estacion" on public."RevisionEstacionesBitacora" (estacion_id);
-- 7) Hallazgos por plaga (interior/voladores y casos exteriores)
