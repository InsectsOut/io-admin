-- 6) Captura por estacion en una revision
create table public."RevisionEstacionesBitacora" (
    id bigint generated by default as identity primary key,
    revision_id bigint not null references public."RevisionesBitacora" (id) on delete cascade,
    estacion_id bigint references public."EstacionesBitacora" (id) on delete
